// Command gentokens turns design/tokens.json into internal/theme/tokens_gen.go:
// a Palette with one field per color, light and dark, and the accent
// presets. Run it from the repository root after tokens.json changes:
//
//	go run ./scripts/gentokens
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
	"strings"
)

type tokens struct {
	Color  map[string]map[string]string `json:"color"`
	Accent struct {
		Default  string            `json:"default"`
		Presets  []string          `json:"presets"`
		DarkLift map[string]string `json:"darkLift"`
	} `json:"accent"`
	Radius map[string]any     `json:"radius"`
	Space  map[string]float64 `json:"space"`
	Font   map[string]any     `json:"font"`
}

var rgba = regexp.MustCompile(`^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([0-9.]+)\s*\)$`)

func colorExpr(v string) (string, bool) {
	v = strings.TrimSpace(v)
	if strings.HasPrefix(v, "#") {
		return fmt.Sprintf("ui.Hex(%q)", v), true
	}
	if m := rgba.FindStringSubmatch(v); m != nil {
		return fmt.Sprintf("ui.RGBA(%s, %s, %s, %s)", m[1], m[2], m[3], m[4]), true
	}
	return "", false
}

func field(key string) string {
	return strings.ToUpper(key[:1]) + key[1:]
}

func main() {
	in := flag.String("in", "design/tokens.json", "tokens file")
	out := flag.String("out", "internal/theme/tokens_gen.go", "Go file to write")
	flag.Parse()

	b, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	var t tokens
	if err := json.Unmarshal(b, &t); err != nil {
		log.Fatal(err)
	}
	light, dark := t.Color["light"], t.Color["dark"]
	var keys []string
	for k, v := range light {
		if _, ok := colorExpr(v); !ok {
			continue // shadows and the color scheme are not colors
		}
		if _, ok := dark[k]; !ok {
			log.Fatalf("color %q has no dark value", k)
		}
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var w bytes.Buffer
	fmt.Fprintf(&w, "// Code generated by go run ./scripts/gentokens from %s; DO NOT EDIT.\n\n", *in)
	fmt.Fprintln(&w, "package theme\n\nimport \"github.com/egoist/mygo/ui\"")
	fmt.Fprintln(&w, "\n// Palette is the design's colors; light and dark share field names.\ntype Palette struct {")
	for _, k := range keys {
		fmt.Fprintf(&w, "\t%s ui.Color\n", field(k))
	}
	fmt.Fprintln(&w, "}")
	for _, side := range []struct {
		name string
		m    map[string]string
	}{{"Light", light}, {"Dark", dark}} {
		fmt.Fprintf(&w, "\n// %s is the %s palette.\nvar %s = Palette{\n", side.name, strings.ToLower(side.name), side.name)
		for _, k := range keys {
			e, ok := colorExpr(side.m[k])
			if !ok {
				log.Fatalf("%s.%s: not a color: %q", side.name, k, side.m[k])
			}
			fmt.Fprintf(&w, "\t%s: %s,\n", field(k), e)
		}
		fmt.Fprintln(&w, "}")
	}
	fmt.Fprintf(&w, "\n// DefaultAccent is the accent the app starts with.\nconst DefaultAccent = %q\n", t.Accent.Default)
	fmt.Fprintf(&w, "\n// AccentPresets are the accents Settings offers.\nvar AccentPresets = %#v\n", t.Accent.Presets)
	fmt.Fprintln(&w, "\n// DarkLift maps an accent to its lighter version on dark backgrounds.\nvar DarkLift = map[string]string{")
	var lifts []string
	for k := range t.Accent.DarkLift {
		lifts = append(lifts, k)
	}
	sort.Strings(lifts)
	for _, k := range lifts {
		fmt.Fprintf(&w, "\t%q: %q,\n", k, t.Accent.DarkLift[k])
	}
	fmt.Fprintln(&w, "}")
	fmt.Fprintf(&w, `
// Metrics from tokens.json.
const (
	TitleBarHeight   = %v
	StatusBarHeight  = %v
	ToastOffset      = %v
	EditorFontSize   = %v
	EditorLineHeight = %v
	UIFontSize       = %v
	SmallFontSize    = %v
)
`, t.Space["titleBar"], t.Space["statusBar"], t.Space["toastOffsetBelowTitleBar"],
		t.Font["editorSize"], t.Font["lineHeightEditor"], t.Font["uiSize"], t.Font["smallSize"])

	src, err := format.Source(w.Bytes())
	if err != nil {
		log.Fatalf("format: %v\n%s", err, w.Bytes())
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
